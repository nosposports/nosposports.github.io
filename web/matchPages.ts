/**
 * 경기별 페이지 (nospo.kr/lck/gen-vs-blg-1115 등) — 검색 유입용.
 * 결과를 암시하는 내용(점수·승패·세트 수·영상 제목·길이)은 절대 넣지 않는다.
 * 여기 글은 유튜브에서 가져오지 않은 자체 작성 콘텐츠.
 */
import type { Match } from '../src/lib/types';
