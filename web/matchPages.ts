import { LEAGUE_PAGES } from './leaguePages';

/** 리그 id → 주소 앞부분 (lol → lck) */
export const leagueSlug = (leagueId: string) =>
  Object.entries(LEAGUE_PAGES).find(([, p]) => p.leagueId === leagueId)?.[0] ?? leagueId;

/** 팀 id → 주소용 이름 (kbl-kt → kt, epl:맨시티 → 맨시티) */
const teamSlug = (id: string) => (id.includes(':') ? id.split(':').slice(1).join(':') : id.replace(/^[a-z]+-/, ''));

/** 경기 주소: /lck/gen-vs-blg-1115 */
export const matchPath = (m: Match) =>
  `/${leagueSlug(m.leagueId ?? 'lol')}/${teamSlug(m.teamA)}-vs-${teamSlug(m.teamB)}-${m.date.slice(5).replace('-', '')}`;

export const findByPath = (all: Match[], route: string) => {
  let r = route;
  try {
    r = decodeURIComponent(route); // 한글 팀 이름 주소는 %EB.. 형태로 들어온다
  } catch {
    /* 잘못된 주소는 그대로 */
  }
  return all.find((m) => matchPath(m) === `/${r}`);
};

const DAYS = ['일', '월', '화', '수', '목', '금', '토'];
export const fmtDate = (d: string) => `${Number(d.slice(0, 4))}년 ${Number(d.slice(5, 7))}월 ${Number(d.slice(8))}일 (${DAYS[new Date(d + 'T00:00:00+09:00').getDay()]})`;

/** 이 경기가 어떤 단계인지 — 대회명·라운드에서 만든 짧은 설명 (결과와 무관) */
export function stageText(m: Match): string[] {
  const lid = m.leagueId ?? 'lol';
  const name = m.league;
  const round = Number(name.match(/(\d+)\s*R/)?.[1] ?? 0);
  const out: string[] = [];
  if (lid === 'lol') {
    if (/결승/.test(name)) out.push('월즈 결승전은 1년 동안 이어진 리그 오브 레전드 시즌의 마지막 경기예요. 이 한 경기로 그해 세계 챔피언이 정해져요.');
    else if (/4강/.test(name)) out.push('월즈 4강은 결승에 오를 팀을 가리는 경기예요. 여기서 이긴 팀만 결승 무대에 서요.');
    else if (/8강/.test(name)) out.push('월즈 8강부터는 지면 바로 대회를 마치는 녹아웃 단계예요.');
    else if (/스위스/.test(name)) out.push('월즈 스위스 스테이지는 전적이 같은 팀끼리 맞붙는 방식이에요. 세 번 이기면 녹아웃에 오르고, 세 번 지면 탈락해요.');
    else out.push(`${name} 경기예요. LCK는 국내 최상위 10개 팀이 겨루는 리그예요.`);
    if (m.bestOf === 5) out.push('5판 3선승제(Bo5)라 3세트에서 끝날 수도, 5세트까지 갈 수도 있어요.');
    else if (m.bestOf === 3) out.push('3판 2선승제(Bo3) 경기예요.');
    else out.push('한 판으로 끝나는 단판(Bo1) 경기예요.');
  } else if (lid === 'kbl') {
    out.push('KBL 정규리그 경기예요. 10분씩 4쿼터, 모두 40분 동안 치러요.');
  } else if (lid === 'kbo') {
    if (/한국시리즈/.test(name)) out.push('한국시리즈는 그해 KBO 우승 팀을 가리는 7전 4선승제 시리즈예요.');
    else if (/플레이오프|준플레이오프|와일드카드/.test(name)) out.push(`${name}는 한국시리즈로 가는 포스트시즌 경기예요.`);
    else out.push('KBO 정규시즌 경기예요. 팀마다 144경기를 치러 순위를 정해요.');
  } else if (lid === 'epl' || lid === 'laliga') {
    const lg = lid === 'epl' ? '프리미어리그' : '라리가';
    const phase = round <= 12 ? '초반' : round <= 26 ? '중반' : '막바지';
    out.push(round ? `${lg} ${round}라운드 경기예요. 20개 팀이 38라운드 동안 겨루는 시즌의 ${phase}이에요.` : `${lg} 경기예요.`);
  } else if (lid === 'kleague') {
    if (round > 33) out.push(`K리그1 ${round}라운드, 순위에 따라 위아래 그룹으로 나뉘어 치르는 파이널 라운드 경기예요.`);
    else out.push(round ? `K리그1 ${round}라운드 경기예요. 33라운드까지 치른 뒤 파이널 라운드로 나뉘어요.` : 'K리그1 경기예요.');
  }
  return out;
}

